function budgetRangeForPrice(price: number): FlashBudgetRange {
  if (price < 100) return "Moins de 100 €";
  if (price <= 200) return "100 à 200 €";
  if (price <= 400) return "200 à 400 €";
  return "Plus de 400 €";
}

export const flashItems: FlashItem[] = flashFiles.map((file, index) => {
  const profile = flashProfilesByImage[index] ?? flashProfiles[index % flashProfiles.length];
  const displayNumber = index >= 4 ? index + 2 : index + 1;
  const reference = `F${String(displayNumber).padStart(3, "0")}`;
  const price = 0;

  return {
    id: `flash-${String(index + 1).padStart(3, "0")}`,
    reference,
    title: profile.title,
    price,
    style: profile.styles.join(" / "),
    size: profile.sizes.join(", "),
    placement: profile.placements.join(", "),
    status: profile.status,
    budgetHint: budgetRangeForPrice(price),
    description: `${profile.title}, prêt à être réservé chez B.Grumpy Tattoo.`,
    styles: profile.styles,
    themes: profile.themes,
    sizes: profile.sizes,
    placements: profile.placements,
    budgetRange: budgetRangeForPrice(price),
    customization: profile.customization,
    keywords: [reference.toLowerCase(), ...profile.keywords],
    image: {
      src: `/api/admin/uploads/flash-${String(index + 1).padStart(3, "0")}.png`,
      alt: `${profile.title} ${reference}`,
    },
  };
});
